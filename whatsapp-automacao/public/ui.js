function icon(name, size = 18) {
  const p = ICON_PATHS[name];
  return p ? `<svg class="ico" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${p}</svg>` : '';
}

// Menu lateral: troca o emoji do início de cada item por um ícone.
document.querySelectorAll('nav button[data-tab]').forEach((b) => {
  const first = b.firstChild;
  if (first?.nodeType === Node.TEXT_NODE) {
    const label = first.textContent.replace(/^[^\p{L}\p{N}]+/u, '').trim();
    const span = document.createElement('span');
    span.className = 'nav-label';
    span.textContent = label;
    b.replaceChild(span, first);
  }
  b.insertAdjacentHTML('afterbegin', icon(b.dataset.tab));
});
document.querySelectorAll('[data-icon]').forEach((el) => el.insertAdjacentHTML('afterbegin', icon(el.dataset.icon)));

/** Atualiza o título da barra superior (chamado por showTab). */
function onTabShown(name) {
  const b = document.querySelector(`nav button[data-tab="${name}"]`);
  if (!b) return;
  let g = b.previousElementSibling;
  while (g && !g.classList.contains('nav-group')) g = g.previousElementSibling;
  document.getElementById('crumbGroup').textContent = g ? g.textContent : 'Vendas';
  document.getElementById('crumbPage').textContent = b.querySelector('.nav-label')?.textContent || '';
  document.body.classList.remove('nav-open');
}

// Gaveta do menu no celular.
document.getElementById('btnMenu').addEventListener('click', () => document.body.classList.toggle('nav-open'));
document.getElementById('navShade').addEventListener('click', () => document.body.classList.remove('nav-open'));
